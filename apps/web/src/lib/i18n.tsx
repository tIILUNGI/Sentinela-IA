const dictionaries: Record<Locale, Dict> = { en, pt }

type I18nCtx = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  tTerm: (value: string | null | undefined) => string
  translateError: (detail: unknown) => string
}

const Ctx = createContext<I18nCtx | null>(null)

function lookup(locale: Locale, key: string): string | undefined {
  return dictionaries[locale][key] ?? dictionaries.en[key]
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem('sentinela_locale')
    return stored === 'pt' ? 'pt' : 'en'
  })

  useEffect(() => {
    localStorage.setItem('sentinela_locale', locale)
    document.documentElement.lang = locale
  }, [locale])

  const setLocale = (next: Locale) => setLocaleState(next)

  const t = (key: string, vars?: Record<string, string | number>) => {
    let value = lookup(locale, key) ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v))
    }
    return value
  }

  const tTerm = (value: string | null | undefined) => {
    if (!value) return ''
    const key = `term.${value}`
    return lookup(locale, key) ?? value
  }

  const translateError = (detail: unknown) => {
    const text = typeof detail === 'string' ? detail : ''
    const lower = text.toLowerCase()
    if (!text) return t('common.error')
    if (lower.includes('invalid credentials') || lower.includes('invalid email or password')) return t('error.invalidCredentials')
    if (lower.includes('email already registered') || lower.includes('already exists')) return t('error.emailRegistered')
    if (lower.includes('not authenticated') || lower.includes('invalid token') || lower.includes('user inactive')) return t('error.notAuthenticated')
    if (lower.includes('insufficient permissions') || lower.includes('not allowed') || lower.includes('not a member') || lower.includes('membership')) return t('error.forbidden')
    if (lower.includes('reset token')) return t('error.resetToken')
    if (lower.includes('not found')) return t('error.notFound')
    if (lower.includes('ai unavailable') || lower.includes('ai_api_key') || lower.includes('provider')) return t('error.aiUnavailable')
    if (lower.includes('network') || lower.includes('failed to fetch')) return t('error.network')
    return locale === 'en' ? text : t('common.error')
  }

  return <Ctx.Provider value={{ locale, setLocale, t, tTerm, translateError }}>{children}</Ctx.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
